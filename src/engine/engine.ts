/**
 * The engine's behaviour version (spec FR-241). Increment it by 1 with any change that alters the
 * deals or move outcomes produced for an existing seed and move sequence.
 */
export const ENGINE_VERSION = 1;

/** Why `applyMove` rejected a move (spec FR-226). */
export type IllegalMoveReason = 'game-over' | 'not-your-turn' | 'unknown-move';

/** Thrown by `applyMove` for a move that is not currently legal. The message names seat and move. */
export class IllegalMoveError extends Error {
  readonly reason: IllegalMoveReason;
  readonly seat: number;
  readonly moveId: string;

  constructor(reason: IllegalMoveReason, seat: number, moveId: string) {
    super(`Illegal move "${moveId}" by seat ${seat}: ${reason}`);
    this.name = 'IllegalMoveError';
    this.reason = reason;
    this.seat = seat;
    this.moveId = moveId;
  }
}

/** Thrown by `createGame` with one entry per failed check (spec FR-211); the message joins them. */
export class InvalidGameSetupError extends Error {
  readonly problems: string[];

  constructor(problems: string[]) {
    super(`Invalid game setup: ${problems.join('; ')}`);
    this.name = 'InvalidGameSetupError';
    this.problems = [...problems];
  }
}

/** The input of `createGame`. `seed` is the game's secret seed (generated by the caller). */
export interface CreateGameInput {
  gameId: string;
  rules: RuleSet;
  seats: SeatInfo[];
  seed: string;
}

/**
 * Collects every FR-211 problem with `input` (empty when valid). A `RuleSetSchema` failure is one
 * problem and skips the checks that read `rules`; a player-range failure skips sequence expansion.
 */
function setupProblems(input: CreateGameInput): string[] {
  const problems: string[] = [];
  const { gameId, rules, seats, seed } = input;
  const seatList: unknown[] = Array.isArray(seats) ? seats : [];

  const parsedRules = RuleSetSchema.safeParse(rules);
  if (!parsedRules.success) {
    problems.push(`rules do not match RuleSetSchema: ${parsedRules.error.message}`);
  } else {
    const { min, max } = parsedRules.data.players;
    if (seatList.length < min || seatList.length > max) {
      problems.push(
        `${seatList.length} seats is outside ${min}–${max} players for rule set ${parsedRules.data.id}`,
      );
    } else {
      try {
        expandHandSequence(parsedRules.data, seatList.length);
      } catch (err) {
        problems.push(err instanceof Error ? err.message : String(err));
      }
    }
  }

  if (!Array.isArray(seats)) problems.push('seats must be an array');
  seatList.forEach((seat, i) => {
    const index = (seat as { seat?: unknown } | null)?.seat;
    if (index !== i) problems.push(`seats[${i}].seat is ${String(index)}, expected ${i}`);
    const parsedSeat = SeatInfoSchema.safeParse(seat);
    if (!parsedSeat.success) {
      problems.push(`seats[${i}] does not match SeatInfoSchema: ${parsedSeat.error.message}`);
    }
  });

  const seen = new Set<string>();
  const duplicates = new Set<string>();
  for (const seat of seatList) {
    const playerId = (seat as { playerId?: unknown } | null)?.playerId;
    if (typeof playerId !== 'string') continue;
    if (seen.has(playerId)) duplicates.add(playerId);
    seen.add(playerId);
  }
  for (const playerId of duplicates) problems.push(`playerId "${playerId}" is used by two seats`);

  if (typeof gameId !== 'string' || gameId === '') problems.push('gameId must not be empty');
  if (typeof seed !== 'string' || seed === '') problems.push('seed must not be empty');
  return problems;
}

/** The seat after `seat` in turn order (spec FR-213). */
function nextSeat(seat: number, seatCount: number): number {
  return (seat + 1) % seatCount;
}

/**
 * Deals hand `handIndex` of `state` (spec FR-213 to FR-217) and returns the new `HandState`.
 * Uses the deal stream `deriveRng(seed, 'deal', handIndex)`: for hand 0 (`previousDealer` `null`)
 * the dealer is `int(0, N − 1)` drawn before the shuffle; otherwise it is `next(previousDealer)`.
 * Card `k` of the shuffled `buildDeck(rules.deck, N)` goes to seat `(dealer + 1 + k) mod N`; the
 * trump card is the next stock card, or the dealer's last card when the whole deck is dealt.
 * Hands are sorted by suit (`rules.deck.suits` order), then rank high→low. Reads only `seed`,
 * `rules`, `seats.length` and `handPlan` from `state`; never mutates it.
 */
function dealHand(state: GameState, handIndex: number, previousDealer: number | null): HandState {
  const { rules } = state;
  const seatCount = state.seats.length;
  const cardsPerPlayer = state.handPlan[handIndex];
  const rng = deriveRng(state.seed, 'deal', handIndex);
  const dealer =
    previousDealer === null ? rng.int(0, seatCount - 1) : nextSeat(previousDealer, seatCount);
  const shuffled = rng.shuffle(buildDeck(rules.deck, seatCount));
  const dealt = seatCount * cardsPerPlayer;

  const hands: Card[][] = Array.from({ length: seatCount }, () => []);
  for (let k = 0; k < dealt; k++) {
    hands[(dealer + 1 + k) % seatCount].push(shuffled[k]);
  }
  const trumpCardInDealerHand = dealt === shuffled.length;
  const trumpCard = { ...shuffled[trumpCardInDealerHand ? dealt - 1 : dealt] };

  const suitOrder = rules.deck.suits;
  for (const hand of hands) {
    hand.sort(
      (a, b) =>
        suitOrder.indexOf(a.suit) - suitOrder.indexOf(b.suit) ||
        compareRanks(rules.deck, b.rank, a.rank),
    );
  }

  const mano = nextSeat(dealer, seatCount);
  return {
    cardsPerPlayer,
    dealer,
    trumpCard,
    trumpCardInDealerHand,
    trumpSuit: trumpCard.suit,
    hands,
    bids: Array.from({ length: seatCount }, () => null),
    tricksWon: Array.from({ length: seatCount }, () => 0),
    currentTrick: { leader: mano, plays: [] },
    toAct: mano,
  };
}

/** The `hand-dealt` event for `hand` (spec FR-212, FR-233). Never contains any seat's cards. */
function handDealtEvent(handIndex: number, hand: HandState): GameEvent {
  return {
    type: 'hand-dealt',
    handIndex,
    dealer: hand.dealer,
    cardsPerPlayer: hand.cardsPerPlayer,
    trumpCard: { ...hand.trumpCard },
    trumpCardInDealerHand: hand.trumpCardInDealerHand,
  };
}

/**
 * Creates a game (spec FR-211, FR-212): validates `input` and throws `InvalidGameSetupError`
 * listing every problem; otherwise returns the initial state (deep copies of `rules` and `seats`,
 * hand 0 dealt, `phase 'bidding'`) and the events `[game-started, hand-dealt]`.
 */
export function createGame(input: CreateGameInput): Transition {
  const problems = setupProblems(input);
  if (problems.length > 0) throw new InvalidGameSetupError(problems);

  const rules = structuredClone(input.rules);
  const seats = structuredClone(input.seats);
  const handPlan = expandHandSequence(rules, seats.length);
  const state: GameState = {
    schemaVersion: 1,
    gameId: input.gameId,
    rules,
    handPlan,
    seats,
    seed: input.seed,
    aiDecisionCount: 0,
    phase: 'bidding',
    handIndex: 0,
    hand: null,
    completedHands: [],
    version: 0,
  };
  state.hand = dealHand(state, 0, null);

  const events: GameEvent[] = [
    { type: 'game-started', seats: structuredClone(seats), handPlan: [...handPlan] },
    handDealtEvent(0, state.hand),
  ];
  return { state, events };
}

/** The seat to act, or `null` at game over (spec FR-218). */
export function currentActor(state: GameState): number | null {
  if (state.phase === 'game-over' || state.hand === null) return null;
  return state.hand.toAct;
}

/** Throws `RangeError` unless `seat` is an integer in `0 … N − 1` (spec FR-219). */
function assertSeatInRange(state: GameState, seat: number): void {
  if (!Number.isInteger(seat) || seat < 0 || seat >= state.seats.length) {
    throw new RangeError(`seat ${seat} is outside 0–${state.seats.length - 1}`);
  }
}

/**
 * The legal moves of `seat` (spec FR-219 to FR-223): `RangeError` for a seat outside `0 … N − 1`;
 * `[]` for a seat that is not the current actor (every seat at game over); otherwise `bid:<n>`
 * moves in ascending order while bidding, or `play:<cardId>` moves in hand order while playing.
 * Returned moves hold copies of the cards, never the state's own objects.
 */
export function legalMoves(state: GameState, seat: number): LegalMove[] {
  assertSeatInRange(state, seat);
  const hand = state.hand;
  if (hand === null || currentActor(state) !== seat) return [];
  if (state.phase === 'bidding') {
    return legalBids(hand, seat, state.rules).map((tricks) => ({
      id: `bid:${tricks}`,
      move: { type: 'bid', seat, tricks },
    }));
  }
  return legalPlays(hand, seat, state.rules, state.rules.deck).map((c) => ({
    id: `play:${cardId(c)}`,
    move: { type: 'play', seat, card: { ...c } },
  }));
}

/**
 * Applies `seat`'s move `moveId` to `state` (spec FR-226 to FR-235) and returns the new state and
 * the events it produced. Checks, in order: `RangeError` for a seat outside `0 … N − 1` (every
 * phase); `IllegalMoveError` `'game-over'`, `'not-your-turn'`, then `'unknown-move'` (the id is not
 * in `legalMoves(state, seat)`). Works on one `structuredClone` of `state`, mutated in place, so
 * the input is never mutated and the result shares no object with it. Runs every automatic
 * transition: bidding closed, trick won, hand completed, then the next deal or game over. Events
 * are emitted in that order and carry copies, never objects of the returned state.
 */
export function applyMove(state: GameState, seat: number, moveId: string): Transition {
  assertSeatInRange(state, seat);
  if (state.phase === 'game-over' || state.hand === null) {
    throw new IllegalMoveError('game-over', seat, moveId);
  }
  if (currentActor(state) !== seat) throw new IllegalMoveError('not-your-turn', seat, moveId);
  const legal = legalMoves(state, seat).find((m) => m.id === moveId);
  if (legal === undefined) throw new IllegalMoveError('unknown-move', seat, moveId);

  const next = structuredClone(state);
  const hand = next.hand as HandState;
  const seatCount = next.seats.length;
  const events: GameEvent[] = [];
  if (next.seats[seat].kind === 'ai') next.aiDecisionCount += 1;

  const move = legal.move;
  if (move.type === 'bid') {
    hand.bids[seat] = move.tricks;
    events.push({ type: 'bid-made', seat, tricks: move.tricks });
    if (seat === hand.dealer) {
      next.phase = 'playing';
      hand.toAct = nextSeat(hand.dealer, seatCount);
    } else {
      hand.toAct = nextSeat(seat, seatCount);
    }
    return { state: next, events };
  }

  const id = cardId(move.card);
  const held = hand.hands[seat];
  const [played] = held.splice(
    held.findIndex((c) => cardId(c) === id),
    1,
  );
  hand.currentTrick.plays.push({ seat, card: played });
  events.push({ type: 'card-played', seat, card: { ...played } });
  if (hand.currentTrick.plays.length < seatCount) {
    hand.toAct = nextSeat(seat, seatCount);
    return { state: next, events };
  }

  // Trick complete (FR-231).
  const plays = hand.currentTrick.plays;
  const winner = trickWinner(plays, hand.trumpSuit, next.rules.deck);
  hand.tricksWon[winner] += 1;
  hand.lastTrick = { winner, plays };
  hand.currentTrick = { leader: winner, plays: [] };
  hand.toAct = winner;
  const trickNumber = hand.tricksWon.reduce((sum, n) => sum + n, 0);
  events.push({ type: 'trick-won', seat: winner, trickNumber });
  if (trickNumber < hand.cardsPerPlayer) return { state: next, events };

  // Hand complete (FR-232).
  const result: HandResult = {
    handIndex: next.handIndex,
    cardsPerPlayer: hand.cardsPerPlayer,
    dealer: hand.dealer,
    trumpSuit: hand.trumpSuit,
    bids: hand.bids.map((b) => b as number),
    tricks: [...hand.tricksWon],
  };
  next.completedHands.push(result);
  events.push({
    type: 'hand-completed',
    handIndex: next.handIndex,
    result: structuredClone(result),
  });

  if (next.handIndex < next.handPlan.length - 1) {
    // Next deal (FR-233).
    next.handIndex += 1;
    next.phase = 'bidding';
    next.hand = dealHand(next, next.handIndex, hand.dealer);
    events.push(handDealtEvent(next.handIndex, next.hand));
  } else {
    // Game over (FR-234): handIndex stays at the last hand.
    next.phase = 'game-over';
    next.hand = null;
    events.push({ type: 'game-over' });
  }
  return { state: next, events };
}

/**
 * The AI random stream for `seat`'s next decision (spec FR-206):
 * `deriveRng(state.seed, 'ai', seat, state.aiDecisionCount)`. The engine never draws from it.
 */
export function aiRng(state: GameState, seat: number): Rng {
  return deriveRng(state.seed, 'ai', seat, state.aiDecisionCount);
}
